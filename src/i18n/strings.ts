/** Keeps assistive tech and translators in sync with the toggle. */
export function applyDocumentLanguage(lang: Language): void {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang === 'en' ? 'en-US' : 'pt-BR';
  }
}
